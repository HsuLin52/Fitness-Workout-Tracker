package com.example.FitnessWorkoutTracker.model;

// Represents the available categories for an exercise.
public enum ExerciseType {

    // Exercises that mainly improve cardiovascular endurance
    CARDIO,

    // Exercises that mainly build muscular strength
    STRENGTH,

    // Exercises that improve mobility and range of motion
    FLEXIBILITY,

    // Exercises related to sports activities
    SPORTS,

    // Used when an exercise does not fit the other categories
    OTHER
}